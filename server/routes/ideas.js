import { Router } from 'express'
import rateLimit from 'express-rate-limit'
import { z } from 'zod'
import { config } from '../config.js'
import { getStore } from '../db/index.js'
import { asyncHandler, HttpError } from '../lib/routeHelpers.js'
import { describeAi, generateIdeasWithAi } from '../services/ai.js'
import { generateIdeas, ideaToText, inferDifficulty, extractSignals, availableConceptCount } from '../services/projectIdeas.js'
import { DIFFICULTIES } from '../../shared/taxonomy.js'

const router = Router()

/**
 * Project idea generation is the most expensive thing HackRadar can do per
 * request (an AI call when configured), so it has its own tight limiter.
 */
const aiLimiter = rateLimit({
  windowMs: config.rateLimit.windowMs,
  max: config.rateLimit.aiMax,
  standardHeaders: true,
  legacyHeaders: false,
  message: {
    error: 'rate_limited',
    message: 'You have generated a lot of ideas already. Please wait a minute before trying again.',
  },
})

const requestSchema = z.object({
  /**
   * Which event to generate for. Both spellings are accepted because the UI
   * knows the slug (it is in the URL) while deep links may carry an id.
   * These must be declared here: Zod strips undeclared keys, so leaving them
   * out silently discards the only field that says which event was requested.
   */
  hackathonId: z.string().trim().min(1).max(120).optional(),
  hackathonSlug: z.string().trim().min(1).max(160).optional(),
  count: z.coerce.number().int().min(1).max(6).default(3),
  /** Incremented by the UI's "Regenerate" button to shift the rule-based pool. */
  offset: z.coerce.number().int().min(0).max(500).default(0),
  difficulty: z
    .union([z.string(), z.array(z.string())])
    .optional()
    .transform((v) => (v === undefined ? [] : Array.isArray(v) ? v : String(v).split(',')))
    .refine(
      (arr) => arr.every((d) => DIFFICULTIES.includes(String(d).toLowerCase())),
      'Unknown difficulty level.',
    ),
  technologies: z
    .union([z.string(), z.array(z.string())])
    .optional()
    .transform((v) => (v === undefined ? [] : Array.isArray(v) ? v : String(v).split(','))),
  /** "ai" attempts the configured provider and falls back to rules on failure. */
  engine: z.enum(['auto', 'rules', 'ai']).default('auto'),
})

async function resolveHackathon(idOrSlug) {
  const store = getStore()
  if (!idOrSlug) return null
  return (
    (await store.getHackathonBySlug(idOrSlug)) ?? (await store.getHackathonById(idOrSlug)) ?? null
  )
}

/**
 * POST /api/ideas/generate
 * Public and unauthenticated by design — anyone can use the generator.
 */
router.post(
  '/generate',
  aiLimiter,
  asyncHandler(async (req, res) => {
    const body = requestSchema.parse(req.body ?? {})
    const hackathon = await resolveHackathon(body.hackathonId ?? body.hackathonSlug)

    if (!hackathon) {
      throw new HttpError(404, 'not_found', 'No hackathon found for that identifier.')
    }

    const useAi = body.engine === 'ai' || body.engine === 'auto'
    let aiResult = null

    if (useAi) {
      aiResult = await generateIdeasWithAi(hackathon, { count: body.count })
    }

    if (aiResult?.ok) {
      return res.json({
        hackathon: { id: String(hackathon.id), title: hackathon.title, slug: hackathon.slug },
        ideas: aiResult.ideas,
        requestedCount: body.count,
        source: 'ai',
        model: aiResult.model,
        aiStatus: describeAi(),
        disclaimer:
          'Generated by an AI model from this event’s published themes. These are not official organiser requirements and do not guarantee selection or a prize.',
      })
    }

    const ideas = generateIdeas(hackathon, {
      count: body.count,
      offset: body.offset,
      difficulty: body.difficulty,
      technologies: body.technologies,
    })

    return res.json({
      hackathon: { id: String(hackathon.id), title: hackathon.title, slug: hackathon.slug },
      ideas,
      requestedCount: body.count,
      // A track with one published theme has a finite number of distinct
      // concepts. Saying so beats padding the panel with near-duplicates.
      availableCount: availableConceptCount(hackathon),
      source: 'rule-based',
      aiStatus: {
        ...describeAi(),
        ...(aiResult?.reason ? { lastAttemptError: aiResult.reason } : {}),
      },
      signals: extractSignals(hackathon),
      difficultyInference: inferDifficulty(extractSignals(hackathon)),
      disclaimer:
        'Suggestions are derived from this event’s published themes, tracks and technologies using deterministic rules. They are not official organiser requirements and do not guarantee selection or a prize.',
    })
  }),
)

/** GET /api/ideas/:idOrSlug/suggestions — lightweight default suggestions. */
router.get(
  '/:idOrSlug/suggestions',
  asyncHandler(async (req, res) => {
    const hackathon = await resolveHackathon(req.params.idOrSlug)
    if (!hackathon) throw new HttpError(404, 'not_found', 'No hackathon found for that identifier.')
    res.json({
      ideas: generateIdeas(hackathon, { count: 3, offset: 0 }),
      source: 'rule-based',
      disclaimer:
        'Rule-based suggestions derived from this event’s published themes and technologies.',
    })
  }),
)

/** POST /api/ideas/format — render a saved/generated idea as copyable text. */
router.post(
  '/format',
  asyncHandler(async (req, res) => {
    const body = z
      .object({
        idea: z.object({
          title: z.string().max(200),
          problem: z.string().max(2000).nullish(),
          targetUsers: z.string().max(1000).nullish(),
          difficulty: z.string().max(40).nullish(),
          estimatedTime: z.string().max(80).nullish(),
          technologies: z.array(z.string().max(80)).max(30).default([]),
          keyFeatures: z.array(z.string().max(500)).max(20).default([]),
          implementationSteps: z.array(z.string().max(500)).max(20).default([]),
          demoTips: z.array(z.string().max(500)).max(10).default([]),
          source: z.string().max(20).optional(),
        }),
        hackathonTitle: z.string().max(300).nullish(),
        organizer: z.string().max(200).nullish(),
      })
      .parse(req.body)

    res.json({
      text: ideaToText(body.idea, {
        title: body.hackathonTitle,
        organizer: body.organizer,
      }),
    })
  }),
)

/** GET /api/ideas/capabilities */
router.get('/capabilities', (_req, res) => {
  res.json(describeAi())
})

export default router
